"""
    record_and_check(pkg::Module; allow = [], workdir = mktempdir(), test_project,
                     test_file, exclude = Symbol[], abstract_params = false)
        -> TrimCheckResult

Record the public calls the test suite of `pkg` makes and check them with
`juliac --trim=safe`, in one step.

This is [`record`](@ref) followed by [`check`](@ref), so the checked signatures are those
of the current tests.

# Arguments
- `pkg::Module`: the package under test.

# Keywords
- `allow = []`: known failures, as for [`check`](@ref).
- `workdir = mktempdir()`: passed to [`check`](@ref). It ends up holding `signatures.txt`,
  the generated `entry.jl` and `juliac.log`, for looking at what was checked.
- `test_project`: the test environment, passed to [`record`](@ref) as `project`.
- `test_file`: passed to [`record`](@ref).
- `exclude = Symbol[]`: passed to [`record`](@ref).
- `abstract_params = false`: passed to [`record`](@ref).

# Returns
A [`TrimCheckResult`](@ref TrimTrace.TrimCheckResult); use [`passed`](@ref) to decide
the outcome.

# Throws
- `ArgumentError`: the tests made no public call of `pkg`.

# Examples
```jldoctest
julia> using TrimFixture  # the demo package in test/fixtures

julia> result = record_and_check(
           TrimFixture;
           allow = ["TrimFixture.unstable(::Int64)"],
           test_project = pkgdir(TrimFixture),
       );

julia> passed(result)
true

julia> length(result.signatures)
6
```

# See also
[`write_ci_workflow`](@ref)
"""
function record_and_check(
    pkg::Module;
    allow = Union{String,Regex}[],
    workdir = mktempdir(),
    test_project = _default_test_project(pkg),
    test_file = joinpath(pkgdir(pkg), "test", "runtests.jl"),
    exclude = Symbol[],
    abstract_params = false,
)
    sigs = record(pkg; project = test_project, test_file, exclude, abstract_params)
    return check(pkg, sigs; allow, workdir)
end

const TRIMTRACE_URL = "https://github.com/BjarkeHautop/TrimTrace.jl"

"""
    write_ci_workflow(pkg_path = pwd(); path, julia = "1", allow = "test/trim-allow.txt")
        -> String

Write a GitHub Actions workflow that runs [`record_and_check`](@ref) on every push and
pull request.

The job records the test suite and compiles the recorded calls with `--trim=safe`, so
every run checks the calls of the current tests. It fails when [`passed`](@ref) is
`false`.

# Arguments
- `pkg_path = pwd()`: the root of the package, holding its `Project.toml`.

# Keywords
- `path`: the workflow file, by default `.github/workflows/TrimTrace.yml` in `pkg_path`.
- `julia = "1"`: the Julia version the job runs (1.13 or later).
- `allow = "test/trim-allow.txt"`: the allowlist file, relative to `pkg_path`. The job
  uses it only when it exists.

# Returns
`path`.

# Notes
The job installs TrimTrace and the package in an environment of their own and
instantiates `test/Project.toml` for [`record`](@ref), which runs the tests there.

# Examples
```jldoctest; filter = r"workflow to .*"
julia> using TrimFixture  # the demo package in test/fixtures

julia> path = write_ci_workflow(pkgdir(TrimFixture); path = tempname());
[ Info: Wrote the TrimTrace CI workflow to /tmp/jl_Ze9ulQjm3U

julia> strip(only(filter(contains("record_and_check"), readlines(path))))
"result = record_and_check(TrimFixture; allow)"
```
"""
function write_ci_workflow(
    pkg_path::AbstractString = pwd();
    path = joinpath(pkg_path, ".github", "workflows", "TrimTrace.yml"),
    julia = "1",
    allow = "test/trim-allow.txt",
)
    name = TOML.parsefile(joinpath(pkg_path, "Project.toml"))["name"]
    has_test_project = isfile(joinpath(pkg_path, "test", "Project.toml"))
    mkpath(dirname(path))
    write(path, _ci_workflow(name, has_test_project, julia, allow))
    @info "Wrote the TrimTrace CI workflow to $path"
    return path
end

function _ci_workflow(name, has_test_project, julia, allow)
    # A package with `[extras]` test dependencies gets a test project generated by `record`.
    instantiate =
        has_test_project ?
        "      - name: Instantiate the test environment\n" *
        "        run: julia --project=test -e 'using Pkg; Pkg.instantiate()'\n" : ""
    return """
    name: TrimTrace

    on:
      push:
        branches:
          - main
        tags: ["*"]
      pull_request:
      workflow_dispatch:

    concurrency:
      group: \${{ github.workflow }}-\${{ github.ref }}
      cancel-in-progress: \${{ startsWith(github.ref, 'refs/pull/') }}

    jobs:
      trimtrace:
        name: Public API under --trim=safe
        runs-on: ubuntu-latest
        steps:
          - uses: actions/checkout@v7
          - uses: julia-actions/setup-julia@v3
            with:
              version: "$julia"
          - uses: julia-actions/cache@v3
          - name: Install TrimTrace and the package
            run: |
              julia --project=@trimtrace -e '
                using Pkg
                Pkg.add(url = "$TRIMTRACE_URL")
                Pkg.develop(path = ".")'
    $(instantiate)      - name: Record the tests and check the calls with --trim=safe
            run: |
              julia --project=@trimtrace -e '
                using TrimTrace, $name
                allow = isfile("$allow") ? "$allow" : String[]
                result = record_and_check($name; allow)
                display(result)
                passed(result) || exit(1)'
    """
end
